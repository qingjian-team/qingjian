/// 读音正好是 `reading` 的写法。
pub fn exact(reading: &str) -> Vec<&'static str> {
    WORDS
        .iter()
        .filter(|(r, _)| *r == reading)
        .map(|(_, word)| *word)
        .collect()
}

/// 读音以 `reading` 开头、更长的词，最多 `limit` 个（边敲边出）。
pub fn starting_with(reading: &str, limit: usize) -> Vec<&'static str> {
    if reading.is_empty() {
        return Vec::new();
    }
    WORDS
        .iter()
        .filter(|(r, _)| r.len() > reading.len() && r.starts_with(reading))
        .map(|(_, word)| *word)
        .take(limit)
        .collect()
}
