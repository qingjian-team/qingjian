//! 系统剪贴板（`NSPasteboard`）的读写。macOS 没有「剪贴板变了」的通知，监听线程按 `changeCount` 轮询；
//! HTML、RTF 按原始字节存，写回去时一字不差，粘贴才能保留格式。文件列表存成一行一个的 `file://` 地址。

use std::borrow::Cow;
use std::path::Path;
use std::sync::atomic::{AtomicIsize, Ordering};

use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{
    NSPasteboard, NSPasteboardItem, NSPasteboardType, NSPasteboardTypeFileURL,
    NSPasteboardTypeHTML, NSPasteboardTypePNG, NSPasteboardTypeRTF, NSPasteboardTypeString,
    NSPasteboardTypeTIFF, NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSData, NSString, NSURL};
use qingjian_clipboard::{
    Capture, ClipFormat, ClipKind, FORMAT_FILES, FORMAT_HTML, FORMAT_PNG, FORMAT_RTF,
    MAX_FILE_LIST_BYTES, MAX_FORMAT_BYTES, MAX_TEXT_CHARS,
};

use super::source::{frontmost_app, total_size};
use crate::picture;
use crate::system::Payload;

/// 原图最多多大（字节）：再大的连读都不读，取出来就要占这么多内存。
const MAX_RAW_IMAGE_BYTES: usize = 200 * 1024 * 1024;

/// 密码管理器等标记「别记录」用的类型（<http://nspasteboard.org> 的约定，加上 1Password 自己的）。
const SENSITIVE_TYPES: [&str; 5] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
];

/// 自己最后一次写完时的 `changeCount`：轮询看到的是它就是自己写的，不记。
static OWN_CHANGE: AtomicIsize = AtomicIsize::new(-1);

fn board() -> Retained<NSPasteboard> {
    NSPasteboard::generalPasteboard()
}

/// 现在的 `changeCount`，每次有人写剪贴板就加一。
pub fn change_count() -> isize {
    board().changeCount()
}

fn has_type(types: &NSArray<NSPasteboardType>, wanted: &NSPasteboardType) -> bool {
    types.iter().any(|kind| kind.isEqualToString(wanted))
}

fn data(board: &NSPasteboard, kind: &NSPasteboardType, limit: usize) -> Option<Vec<u8>> {
    let data = board.dataForType(kind)?;
    if data.len() > limit {
        tracing::info!(size = data.len(), "clipboard format too large to record");
        return None;
    }
    Some(data.to_vec())
}

/// 读这次复制的内容。文件优先（访达复制文件时还附带图标和文件名），其次文字，最后才是图片。
/// `records` 按来源程序判断要不要记，不记的内容根本不读。
pub fn read_capture(count: isize, records: impl Fn(&str) -> bool) -> Option<Capture> {
    if count == OWN_CHANGE.load(Ordering::Relaxed) {
        return None;
    }
    let board = board();
    let types = board.types()?;
    if SENSITIVE_TYPES
        .iter()
        .any(|name| has_type(&types, &NSString::from_str(name)))
    {
        return None;
    }
    let source = frontmost_app().unwrap_or_default();
    if !records(&source) {
        return None;
    }
    // SAFETY: 系统定义的常量字符串，进程存活期间一直有效。
    let (file_url, string, html, rtf, png, tiff) = unsafe {
        (
            NSPasteboardTypeFileURL,
            NSPasteboardTypeString,
            NSPasteboardTypeHTML,
            NSPasteboardTypeRTF,
            NSPasteboardTypePNG,
            NSPasteboardTypeTIFF,
        )
    };
    if has_type(&types, file_url) {
        // 文件列表超限时整条不记，不能往下落到文字上，记成另一样东西
        return read_files(&board, file_url, source);
    }
    if has_type(&types, string) {
        let text = board.stringForType(string)?;
        // NSString 的长度按 UTF-16 算，一个字符最多两个单元
        if text.length() > MAX_TEXT_CHARS * 2 {
            tracing::info!("clipboard content too large to record");
            return None;
        }
        let text = text.to_string();
        if !text.trim().is_empty() {
            let mut formats = Vec::new();
            if let Some(bytes) = data(&board, html, MAX_FORMAT_BYTES) {
                formats.push(ClipFormat::new(FORMAT_HTML, bytes));
            }
            if let Some(bytes) = data(&board, rtf, MAX_FORMAT_BYTES) {
                formats.push(ClipFormat::new(FORMAT_RTF, bytes));
            }
            return Some(Capture::text(text, source, formats));
        }
    }
    let image_size = [png, tiff]
        .into_iter()
        .filter(|kind| has_type(&types, kind))
        .filter_map(|kind| board.dataForType(kind))
        .map(|data| data.len())
        .max()?;
    if image_size > MAX_RAW_IMAGE_BYTES {
        tracing::info!("clipboard content too large to record");
        return None;
    }
    let (png, thumbnail) = read_image()?;
    Some(Capture::image(png, thumbnail, source))
}

fn read_files(
    board: &NSPasteboard,
    file_url: &NSPasteboardType,
    source: String,
) -> Option<Capture> {
    let items = board.pasteboardItems()?;
    let urls: Vec<String> = items
        .iter()
        .filter_map(|item| item.stringForType(file_url))
        .map(|url| url.to_string())
        .collect();
    let raw = urls.join("\n").into_bytes();
    if raw.len() > MAX_FILE_LIST_BYTES {
        tracing::info!("clipboard content too large to record");
        return None;
    }
    let paths = file_paths(&urls);
    if paths.is_empty() {
        return None;
    }
    let size = total_size(&paths);
    Some(Capture::files(&paths, raw, source, size))
}

/// `file://` 地址 → 本地路径；认不出的跳过。
fn file_paths(urls: &[String]) -> Vec<String> {
    urls.iter()
        .filter_map(|url| NSURL::URLWithString(&NSString::from_str(url)))
        .filter_map(|url| url.path())
        .map(|path| path.to_string())
        .collect()
}

fn read_image() -> Option<(Vec<u8>, Vec<u8>)> {
    let image = arboard::Clipboard::new().ok()?.get_image().ok()?;
    picture::encode(image.width as u32, image.height as u32, &image.bytes)
}

/// 写回系统剪贴板，记下这次写完的 `changeCount`，监听线程据此认出是自己写的。
pub fn write_payload(payload: &Payload) {
    match payload.kind {
        ClipKind::Image => write_image(payload),
        ClipKind::Files => write_files(payload),
        _ => write_text(payload),
    }
    OWN_CHANGE.store(change_count(), Ordering::Relaxed);
}

fn write_text(payload: &Payload) {
    let board = board();
    board.clearContents();
    // SAFETY: 系统定义的常量字符串。
    let (string, html, rtf) = unsafe {
        (
            NSPasteboardTypeString,
            NSPasteboardTypeHTML,
            NSPasteboardTypeRTF,
        )
    };
    board.setString_forType(&NSString::from_str(&payload.text), string);
    for format in &payload.formats {
        let kind = match format.name.as_str() {
            FORMAT_HTML => html,
            FORMAT_RTF => rtf,
            _ => continue,
        };
        board.setData_forType(Some(&NSData::with_bytes(&format.data)), kind);
    }
}

fn write_files(payload: &Payload) {
    let Some(files) = payload
        .formats
        .iter()
        .find(|format| format.name == FORMAT_FILES)
    else {
        return;
    };
    let urls: Vec<String> = String::from_utf8_lossy(&files.data)
        .lines()
        .map(str::to_owned)
        .collect();
    // 文件都还在才写：目标程序读到失效的路径就什么都粘贴不了
    if !file_paths(&urls)
        .iter()
        .all(|path| Path::new(path).exists())
    {
        tracing::warn!("copied files no longer exist");
        return;
    }
    // SAFETY: 系统定义的常量字符串。
    let file_url = unsafe { NSPasteboardTypeFileURL };
    let items: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = urls
        .iter()
        .map(|url| {
            let item = NSPasteboardItem::new();
            item.setString_forType(&NSString::from_str(url), file_url);
            ProtocolObject::from_retained(item)
        })
        .collect();
    let board = board();
    board.clearContents();
    if !board.writeObjects(&NSArray::from_retained_slice(&items)) {
        tracing::warn!("clipboard file write failed");
    }
}

fn write_image(payload: &Payload) {
    let decoded = payload
        .formats
        .iter()
        .find(|format| format.name == FORMAT_PNG)
        .and_then(|format| picture::decode(&format.data));
    let Some((width, height, rgba)) = decoded else {
        tracing::warn!("clipboard image missing or unreadable");
        return;
    };
    let image = arboard::ImageData {
        width: width as usize,
        height: height as usize,
        bytes: Cow::Owned(rgba),
    };
    if let Err(error) = arboard::Clipboard::new().and_then(|mut board| board.set_image(image)) {
        tracing::warn!(%error, "clipboard image write failed");
    }
}
